/**
 * @jest-environment node
 */
/* eslint-disable @typescript-eslint/no-explicit-any */
import { readFileSync } from 'fs'
import {
  run,
  IGitHubClient,
  SuggestedIssue,
  isDuplicate,
  GitHubClient,
} from '../../../scripts/create-review-issues'
import { execSync } from 'child_process'

// Mock the GitHubClient
class MockGitHubClient implements IGitHubClient {
  getOpenIssues = jest.fn().mockReturnValue([])
  createIssue = jest.fn()
}

// Mock fs.readFileSync
jest.mock('fs', () => ({
  ...jest.requireActual('fs'),
  readFileSync: jest.fn(),
}))

// Mock child_process.execSync
jest.mock('child_process', () => ({
  ...jest.requireActual('child_process'),
  execSync: jest.fn(),
}))

describe('create-review-issues script', () => {
  let client: MockGitHubClient
  const prNumber = '123'
  const reviewFilePath = 'review_result.json'

  beforeEach(() => {
    client = new MockGitHubClient()
    jest.clearAllMocks()
  })

  it('should run without crashing when there are no suggested issues', async () => {
    const reviewResult = {
      reviewComment: 'No issues found.',
      labels: [],
      verdict: 'approve',
      suggestedIssues: [],
    }
    ;(readFileSync as jest.Mock).mockReturnValue(JSON.stringify(reviewResult))

    await expect(run(client, prNumber, reviewFilePath)).resolves.not.toThrow()
    expect(client.getOpenIssues).not.toHaveBeenCalled()
    expect(client.createIssue).not.toHaveBeenCalled()
  })

  it('should create issues for all valid suggestions', async () => {
    const reviewResult = {
      reviewComment: 'Found some issues.',
      labels: [],
      verdict: 'comment',
      suggestedIssues: [
        {
          title: 'Refactor the authentication service',
          description: 'The auth service is too complex.',
          type: 'technical-debt',
          priority: 'high',
        },
        {
          title: 'Fix the button alignment',
          description: 'The button is not aligned correctly.',
          type: 'frontend-improvement',
          priority: 'low',
        },
      ],
    }
    ;(readFileSync as jest.Mock).mockReturnValue(JSON.stringify(reviewResult))

    await run(client, prNumber, reviewFilePath)

    expect(client.getOpenIssues).toHaveBeenCalledWith('bot-generated')
    expect(client.createIssue).toHaveBeenCalledTimes(2)
    expect(client.createIssue).toHaveBeenCalledWith(
      reviewResult.suggestedIssues[0],
      expect.any(Object)
    )
    expect(client.createIssue).toHaveBeenCalledWith(
      reviewResult.suggestedIssues[1],
      expect.any(Object)
    )
  })

  it('should skip duplicate issues', async () => {
    const newIssue: SuggestedIssue = {
      title: 'Refactor the authentication service',
      description: 'The auth service is too complex.',
      type: 'technical-debt',
      priority: 'high',
    }
    const existingIssues = [
      {
        number: 1,
        title: 'Refactor the authentication service',
        state: 'open',
        body: 'The auth service is too complex.\n\n---\n*Generated by Gemini Code Review*',
      },
    ]

    expect(isDuplicate(newIssue, existingIssues)).toBe(true)
  })

  describe('GitHubClient', () => {
    let ghClient: GitHubClient

    beforeEach(() => {
      ghClient = new GitHubClient()
    })

    it('should call gh issue create with the correct parameters', () => {
      const issue: SuggestedIssue = {
        title: 'Test Issue',
        description: 'Test Description',
        type: 'bug',
        priority: 'medium',
      }
      const context = {
        repo: 'test/repo',
        prNumber: '456',
        commitHash: 'abcdefg',
        branchName: 'test-branch',
      }

      ;(execSync as jest.Mock).mockReturnValue('https://github.com/test/repo/issues/1')

      ghClient.createIssue(issue, context)

      expect(execSync).toHaveBeenCalledWith(
        expect.stringContaining('gh issue create'),
        expect.any(Object)
      )
      expect(execSync).toHaveBeenCalledWith(
        expect.stringContaining('--label "bot-generated,triage-needed,type-bug,priority-medium"'),
        expect.any(Object)
      )
    })
  })
})
