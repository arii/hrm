/**
 * @jest-environment node
 */

import { readFileSync } from 'fs'
import {
  run,
  IGitHubClient,
  SuggestedIssue,
  GitHubClient,
  isLowQualityIssue,
} from '../../../scripts/create-review-issues'
import { spawnSync } from 'child_process'

// Mock the GitHubClient
class MockGitHubClient implements IGitHubClient {
  getRecentIssues = jest.fn().mockReturnValue([])
  createIssue = jest.fn()
}

// Mock fs.readFileSync
jest.mock('fs', () => ({
  ...jest.requireActual('fs'),
  readFileSync: jest.fn(),
}))

// Mock child_process.spawnSync
jest.mock('child_process', () => ({
  ...jest.requireActual('child_process'),
  spawnSync: jest.fn(),
}))

describe('create-review-issues script', () => {
  let client: MockGitHubClient
  const prNumber = '123'
  const reviewFilePath = 'review_result.json'

  beforeEach(() => {
    client = new MockGitHubClient()
    jest.clearAllMocks()
  })

  it('should run without crashing when there are no suggested issues', async () => {
    const reviewResult = {
      reviewComment: 'No issues found.',
      labels: [],
      verdict: 'approve',
      suggestedIssues: [],
    }
    ;(readFileSync as jest.Mock).mockImplementation((filePath) => {
      if (filePath.endsWith(reviewFilePath)) {
        return JSON.stringify(reviewResult)
      }
      if (filePath.endsWith('ai_slop_words.txt')) {
        return 'delve\nrobust\nleverage'
      }
      return ''
    })

    await expect(run(client, prNumber, reviewFilePath)).resolves.not.toThrow()
    expect(client.getRecentIssues).not.toHaveBeenCalled()
    expect(client.createIssue).not.toHaveBeenCalled()
  })

  it('should create issues for all valid suggestions', async () => {
    const reviewResult = {
      reviewComment: 'Found some issues.',
      labels: [],
      verdict: 'comment',
      suggestedIssues: [
        {
          title: 'Refactor the authentication service',
          description:
            'The auth service is too complex and should be refactored to improve maintainability.',
          type: 'refactor',
          priority: 'high',
          isPreExisting: true,
        },
        {
          title: 'Fix the button alignment',
          description:
            'The button is not aligned correctly on the main page, which affects the user experience.',
          type: 'enhancement',
          priority: 'low',
          isPreExisting: true,
        },
      ],
    }
    ;(readFileSync as jest.Mock).mockImplementation((filePath) => {
      if (filePath.endsWith(reviewFilePath)) {
        return JSON.stringify(reviewResult)
      }
      if (filePath.endsWith('ai_slop_words.txt')) {
        return 'delve\nrobust\nleverage'
      }
      return ''
    })

    await run(client, prNumber, reviewFilePath)

    expect(client.getRecentIssues).toHaveBeenCalledWith('bot-generated')
    expect(client.createIssue).toHaveBeenCalledTimes(2)
    expect(client.createIssue).toHaveBeenCalledWith(
      reviewResult.suggestedIssues[0],
      expect.any(Object)
    )
    expect(client.createIssue).toHaveBeenCalledWith(
      reviewResult.suggestedIssues[1],
      expect.any(Object)
    )
  })

  it('should skip duplicate issues if state is open', async () => {
    const reviewResult = {
      reviewComment: 'Found some issues.',
      labels: [],
      verdict: 'comment',
      suggestedIssues: [
        {
          title: 'Refactor the authentication service',
          description:
            'The auth service is too complex and should be refactored to improve maintainability.',
          type: 'refactor',
          priority: 'high',
          isPreExisting: true,
        },
      ],
    }
    ;(readFileSync as jest.Mock).mockImplementation((filePath) => {
      if (filePath.endsWith(reviewFilePath)) {
        return JSON.stringify(reviewResult)
      }
      if (filePath.endsWith('ai_slop_words.txt')) {
        return 'delve\nrobust\nleverage'
      }
      return ''
    })
    client.getRecentIssues.mockReturnValue([
      {
        number: 1,
        title: 'Refactor the authentication service',
        state: 'open',
        body: 'Different description.\n\n---\n*Generated by Gemini Code Review*',
      },
    ])

    await run(client, prNumber, reviewFilePath)
    expect(client.createIssue).not.toHaveBeenCalled()
  })

  it('should NOT skip fuzzy duplicate issues if existing is closed', async () => {
    const reviewResult = {
      reviewComment: 'Found some issues.',
      labels: [],
      verdict: 'comment',
      suggestedIssues: [
        {
          title: 'Refactor the authentication service',
          description:
            'The auth service is too complex and should be refactored to improve maintainability.',
          type: 'refactor',
          priority: 'high',
          isPreExisting: true,
        },
      ],
    }
    ;(readFileSync as jest.Mock).mockImplementation((filePath) => {
      if (filePath.endsWith(reviewFilePath)) {
        return JSON.stringify(reviewResult)
      }
      if (filePath.endsWith('ai_slop_words.txt')) {
        return 'delve\nrobust\nleverage'
      }
      return ''
    })
    client.getRecentIssues.mockReturnValue([
      {
        number: 1,
        title: 'Refactor the authentication service',
        state: 'closed',
        body: 'Different description.\n\n---\n*Generated by Gemini Code Review*',
      },
    ])

    await run(client, prNumber, reviewFilePath)
    expect(client.createIssue).toHaveBeenCalledTimes(1)
  })

  describe('GitHubClient', () => {
    let ghClient: GitHubClient

    beforeEach(() => {
      ghClient = new GitHubClient()
      ;(spawnSync as jest.Mock).mockReturnValue({
        status: 0,
        stdout: '[]',
        stderr: '',
      })
    })

    it('should call gh issue create with the correct parameters', () => {
      const issue: SuggestedIssue = {
        title: 'Test Issue',
        description:
          'Test Description that is long enough to pass the quality check.',
        type: 'bug',
        priority: 'medium',
        isPreExisting: true,
      }
      const context = {
        repo: 'test/repo',
        prNumber: '456',
        commitHash: 'abcdefg',
        branchName: 'test-branch',
      }
      ;(spawnSync as jest.Mock).mockImplementation((_command, args) => {
        if (args.includes('label') && args.includes('list')) {
          return { status: 0, stdout: '[]', stderr: '' }
        }
        if (args.includes('issue') && args.includes('create')) {
          return {
            status: 0,
            stdout: 'https://github.com/test/repo/issues/1',
            stderr: '',
          }
        }
        return { status: 0, stdout: '', stderr: '' }
      })

      ghClient.createIssue(issue, context)
      expect(spawnSync).toHaveBeenCalledWith(
        'gh',
        expect.arrayContaining(['issue', 'create']),
        expect.any(Object)
      )
      expect(spawnSync).toHaveBeenCalledWith(
        'gh',
        expect.arrayContaining([
          '--label',
          'bot-generated,triage-needed,bug,priority:medium',
        ]),
        expect.any(Object)
      )
    })

    it('should handle titles with special characters safely', () => {
      const issue: SuggestedIssue = {
        title: "Fix: `rm -rf /` shouldn't run",
        description:
          'A very serious bug that needs to be fixed right away because it is a security vulnerability.',
        type: 'bug',
        priority: 'high',
        isPreExisting: true,
      }
      const context = { repo: 'test/repo', prNumber: '789' }
      ghClient.createIssue(issue, context)

      const lastCall = (spawnSync as jest.Mock).mock.calls.find(
        (call) => call[1].includes('issue') && call[1].includes('create')
      )

      expect(lastCall[0]).toBe('gh')
      expect(lastCall[1]).toContain('--title')
      const titleIndex = lastCall[1].indexOf('--title')
      expect(lastCall[1][titleIndex + 1]).toBe(issue.title)
    })
  })
})

describe('isLowQualityIssue', () => {
  const slopWords = ['delve', 'robust', 'leverage']
  const slopPattern = new RegExp(`\\b(?:${slopWords.join('|')})\\b`, 'i')

  it('should flag issues with 3 or more unique "slop" words as low-quality', () => {
    const issue = {
      title: 'This is a robust solution',
      description:
        'We need to delve into this issue and leverage our resources to fix this problem.',
      type: 'refactor',
      priority: 'medium',
      isPreExisting: true,
    }
    expect(isLowQualityIssue(issue, slopPattern)).toBe(true)
  })

  it('should NOT flag issues with only 1 or 2 unique "slop" words', () => {
    const issue = {
      title: 'This is a robust solution',
      description:
        'We need to fix this issue in the authentication service. It should be long enough.',
      type: 'refactor',
      priority: 'medium',
      isPreExisting: true,
    }
    expect(isLowQualityIssue(issue, slopPattern)).toBe(false)
  })

  it('should NOT flag issues with 3 identical "slop" words but fewer than 3 unique ones', () => {
    const issue = {
      title: 'Robust robust robust',
      description:
        'This is a robust description of a robust problem that requires a robust solution.',
      type: 'refactor',
      priority: 'medium',
      isPreExisting: true,
    }
    expect(isLowQualityIssue(issue, slopPattern)).toBe(false)
  })

  it('should flag issues with short descriptions as low-quality', () => {
    const issue = {
      title: 'This is a trivial issue',
      description: 'This is a short description.',
      type: 'refactor',
      priority: 'medium',
      isPreExisting: true,
    }
    expect(isLowQualityIssue(issue, slopPattern)).toBe(true)
  })

  it('should not flag high-quality issues', () => {
    const issue = {
      title: 'This is a high-quality issue',
      description:
        'This is a long and detailed description of the issue. It does not contain any "slop" words.',
      type: 'refactor',
      priority: 'medium',
      isPreExisting: true,
    }
    expect(isLowQualityIssue(issue, slopPattern)).toBe(false)
  })

  it('should handle an empty slop words list', () => {
    const issue = {
      title: 'This is a high-quality issue',
      description:
        'This is a long and detailed description of the issue. It does not contain any "slop" words.',
      type: 'refactor',
      priority: 'medium',
      isPreExisting: true,
    }
    expect(isLowQualityIssue(issue, null)).toBe(false)
  })
})
