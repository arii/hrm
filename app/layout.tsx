import type { Metadata } from 'next'
import { Inter, Roboto_Mono } from 'next/font/google'
import { AppRouterCacheProvider } from '@mui/material-nextjs/v15-appRouter'
import { ThemeProvider } from '@mui/material/styles'
import CssBaseline from '@mui/material/CssBaseline'
import theme from '../theme/theme'
import Main from './main'
import './globals.css'
import { UserSettingsProvider } from '@/context/UserSettingsContext'
import { WebSocketProvider } from '@/context/WebSocketContext'

const inter = Inter({
  subsets: ['latin'],
  variable: '--font-inter',
  display: 'swap',
})

const roboto_mono = Roboto_Mono({
  subsets: ['latin'],
  variable: '--font-roboto-mono',
  display: 'swap',
})

export const metadata: Metadata = {
  title: 'HRM | Real-Time Heart Rate Monitor',
  description: 'Generated by create next app',
}

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode
}>) {
  return (
    <html lang="en">
      <head>
        {/* Preload the primary display font to prevent FOUT. */}
        <link
          rel="preload"
          href="/assets/digital-7-mono.ttf"
          as="font"
          type="font/ttf"
          crossOrigin="anonymous"
        />
        {/*
          Workaround for a `ReferenceError: DOCS_timing is not defined`
          error that originates from scripts within an embedded Google Doc.
          This initializes `window.DOCS_timing` as an empty object before the
          Google Doc script runs, preventing the error. This is not related
          to any HRM application functionality.
        */}
        <script
          dangerouslySetInnerHTML={{
            __html: `
              window.DOCS_timing = window.DOCS_timing || {};
            `,
          }}
        />
      </head>
      <body className={`${inter.variable} ${roboto_mono.variable}`}>
        <AppRouterCacheProvider>
          <ThemeProvider theme={theme}>
            <CssBaseline />
            <UserSettingsProvider>
              <WebSocketProvider>
                <Main>{children}</Main>
              </WebSocketProvider>
            </UserSettingsProvider>
          </ThemeProvider>
        </AppRouterCacheProvider>
      </body>
    </html>
  )
}
