import type { Metadata } from 'next'
import { Inter, Roboto_Mono } from 'next/font/google'
import Main from './main'
import './globals.css'
const inter = Inter({
  subsets: ['latin'],
  variable: '--font-inter',
  display: 'swap',
})

const roboto_mono = Roboto_Mono({
  subsets: ['latin'],
  variable: '--font-roboto-mono',
  display: 'swap',
})

export const metadata: Metadata = {
  title: 'HRM | Real-Time Heart Rate Monitor',
  description: 'Generated by create next app',
}

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode
}>) {
  return (
    <html lang="en">
      <head>
        {/* Preload the primary display font to prevent FOUT. */}
        <link
          rel="preload"
          href="/assets/digital-7-mono.ttf"
          as="font"
          type="font/ttf"
          crossOrigin="anonymous"
        />
        {/*
          Workaround for a ReferenceError in embedded Google Docs script.
          This script initializes `window.DOCS_timing` to prevent an error from
          Google's own scripts, and is not related to HRM application functionality.
          It's placed in the <head> to ensure it executes before the Google Docs iframe
          is parsed.
        */}
        <script
          dangerouslySetInnerHTML={{
            __html: `
              window.DOCS_timing = window.DOCS_timing || {};
            `,
          }}
        />
      </head>
      <body className={`${inter.variable} ${roboto_mono.variable}`}>
        <Main>{children}</Main>
      </body>
    </html>
  )
}
