import type { Metadata } from 'next';
import { Inter, Roboto_Mono } from 'next/font/google';
import BottomNavBar from '@/components/BottomNavBar';
import ErrorBoundary from '@/components/ErrorBoundary';
import ErrorDisplay from '@/components/ErrorDisplay';
import ErrorFallback from '@/components/ErrorFallback';
import Footer from '@/components/Footer';
import Providers from '@/components/Providers';
import ThemeRegistry from '@/components/ThemeRegistry/ThemeRegistry';
import TimerSoundProvider from '@/components/TimerSoundProvider';
import { ErrorProvider } from '@/context/ErrorContext';
import { UserSettingsProvider } from '@/context/UserSettingsContext';
import './globals.css';
import { headers } from 'next/headers';

const inter = Inter({
  subsets: ['latin'],
  variable: '--font-inter',
});

const roboto_mono = Roboto_Mono({
  subsets: ['latin'],
  variable: '--font-roboto-mono',
});

export const metadata: Metadata = {
  title: 'HRM | Real-Time Heart Rate Monitor',
  description: 'Generated by create next app',
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // Read the CSRF token from the request headers.
  // The middleware is responsible for setting this header.
  const csrfToken = headers().get('x-csrf-token');

  return (
    <html lang="en">
      <head>
        {/* Preload the primary display font to prevent FOUT. */}
        <link
          rel="preload"
          href="/assets/digital-7-mono.ttf"
          as="font"
          type="font/ttf"
          crossOrigin="anonymous"
        />
        {/* Render the CSRF token in a meta tag for client-side access. */}
        {csrfToken && <meta name="csrf-token" content={csrfToken} />}
      </head>
      <body className={`${inter.variable} ${roboto_mono.variable}`}>
        {/* ThemeRegistry now contains all the logic */}
        <ThemeRegistry options={{ key: 'mui' }}>
          <ErrorProvider>
            <Providers>
              <UserSettingsProvider>
                <ErrorBoundary fallback={<ErrorFallback />}>
                  <TimerSoundProvider>{children}</TimerSoundProvider>
                </ErrorBoundary>
              </UserSettingsProvider>
            </Providers>
            <ErrorDisplay />
          </ErrorProvider>
          <Footer />
          <BottomNavBar />
        </ThemeRegistry>
      </body>
    </html>
  );
}
